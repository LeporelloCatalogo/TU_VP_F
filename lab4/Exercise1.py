'''
Напишете програма, в която потребителят въвежда изречение. Програмата
трябва да раздели изречението на отделни думи, да премахне дублиращите се с
помощта на множество (set) и да изведе на екрана броя на уникалните думите,
както и самите уникални думи, подредени по азбучен ред.
'''

dumi = input("Type your sentence: ").split()

dumi = sorted(set(dumi))

print(f"Amount of unique elements: {len(dumi)}")
for i in dumi:
    print(i)



